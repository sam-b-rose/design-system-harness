import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { basename, dirname, join, relative } from "node:path";
import ts from "typescript";
import config from "../ds.config";
import { componentDir, componentFile, listComponents } from "../cli/lib/components";
import { componentDocPath } from "../cli/lib/docs";
import { exportNames } from "../cli/lib/exports";
import { fromRoot } from "../cli/lib/paths";
import { listTokens } from "../cli/lib/tokens";
import { loadCompilerOptions } from "../cli/lib/typescript";

const SCRIPT = "scripts/build-docs.ts";
const MARKDOWN_HEADER = `<!-- Generated by ${SCRIPT}. Do not edit. -->`;
const CSS_HEADER = `/* Generated by ${SCRIPT}. Do not edit. */`;
const TOKENS_CSS = "packages/ds/src/tokens/tokens.css";

interface Prop {
  name: string;
  type: string;
  required: boolean;
  defaultValue: string;
  description: string;
}

interface ComponentDoc {
  name: string;
  summary: string;
  markdown: string;
}

function readProps(program: ts.Program, name: string): Prop[] {
  const checker = program.getTypeChecker();
  const source = program.getSourceFile(componentFile(name));
  const moduleSymbol = source && checker.getSymbolAtLocation(source);
  const propsSymbol =
    moduleSymbol && checker.getExportsOfModule(moduleSymbol).find((symbol) => symbol.name === `${name}Props`);
  if (!propsSymbol) {
    throw new Error(`${name}.tsx must export an interface or type named ${name}Props.`);
  }

  return checker
    .getDeclaredTypeOfSymbol(propsSymbol)
    .getProperties()
    .map((property) => {
      const defaultTag = property.getJsDocTags(checker).find((tag) => tag.name === "default");
      return {
        name: property.name,
        type: describeType(checker, property),
        required: (property.flags & ts.SymbolFlags.Optional) === 0,
        defaultValue: ts.displayPartsToString(defaultTag?.text),
        description: ts.displayPartsToString(property.getDocumentationComment(checker)).replace(/\s+/g, " "),
      };
    });
}

function describeType(checker: ts.TypeChecker, property: ts.Symbol): string {
  const type = checker.getNonNullableType(checker.getTypeOfSymbol(property));
  const members = type.isUnion() ? type.types : [type];
  if (members.every((member) => member.isStringLiteral())) {
    return members.map((member) => checker.typeToString(member)).join(" | ");
  }
  const declaration = property.valueDeclaration;
  if (declaration && ts.isPropertySignature(declaration) && declaration.type) {
    return declaration.type.getText();
  }
  return checker.typeToString(type);
}

function propsTable(props: Prop[]): string {
  const cell = (text: string) => text.replace(/\|/g, "\\|");
  const code = (text: string) => (text ? `\`${cell(text)}\`` : "");
  const rows = props.map(
    (prop) =>
      `| \`${prop.name}\` | ${code(prop.type)} | ${prop.required ? "yes" : "no"} | ${code(prop.defaultValue)} | ${cell(prop.description)} |`,
  );
  return ["| Prop | Type | Required | Default | Description |", "| --- | --- | --- | --- | --- |", ...rows].join("\n");
}

function readExamples(name: string): string {
  const dir = join(componentDir(name), "examples");
  if (!existsSync(dir)) return "";
  return readdirSync(dir)
    .filter((file) => file.endsWith(".tsx"))
    .sort()
    .map((file) => {
      const words = basename(file, ".tsx").replace(/-/g, " ");
      const title = words[0].toUpperCase() + words.slice(1);
      const code = readFileSync(join(dir, file), "utf8").trim();
      return `### ${title}\n\n\`\`\`tsx\n${code}\n\`\`\``;
    })
    .join("\n\n");
}

function buildComponentDoc(program: ts.Program, name: string): ComponentDoc {
  const docsFile = join(componentDir(name), `${name}.docs.md`);
  if (!existsSync(docsFile)) {
    throw new Error(`Missing ${relative(fromRoot(), docsFile)}. Every component needs a co-located docs file.`);
  }
  const authored = readFileSync(docsFile, "utf8").trim();
  const firstSection = authored.search(/^## /m);
  const intro = (firstSection === -1 ? authored : authored.slice(0, firstSection)).trim();
  const sections = firstSection === -1 ? "" : authored.slice(firstSection).trim();
  const examples = readExamples(name);

  const markdown = [
    MARKDOWN_HEADER,
    `# ${name}`,
    intro,
    `## Import\n\n\`\`\`tsx\nimport { ${name} } from "${config.alias}";\n\`\`\``,
    `## Props\n\n${propsTable(readProps(program, name))}`,
    examples && `## Examples\n\n${examples}`,
    sections,
  ]
    .filter(Boolean)
    .join("\n\n");

  return { name, summary: intro.split("\n")[0], markdown: `${markdown}\n` };
}

function buildTokensDoc(): string {
  const rows = listTokens().map(
    (entry) => `| \`token("${entry.path}")\` | \`${entry.cssVar}\` | \`${entry.value}\` | ${entry.category} |`,
  );
  return [
    MARKDOWN_HEADER,
    `# ${config.name} tokens`,
    `> Every design token. In TSX, call \`token("<path>")\` from \`${config.alias}\`. In CSS, use \`var(<css variable>)\`. Never write the raw value.`,
    ["| TSX | CSS variable | Value | Category |", "| --- | --- | --- | --- |", ...rows].join("\n"),
    "",
  ].join("\n\n");
}

function buildTokensCss(): string {
  const declarations = listTokens().map((entry) => `  ${entry.cssVar}: ${entry.value};`);
  return [CSS_HEADER, ":root {", ...declarations, "}", ""].join("\n");
}

function buildIndex(docs: ComponentDoc[]): string {
  const inline = (names: string[]) => names.map((name) => `\`${name}\``).join(", ");
  const hallucinations = Object.entries(config.knownHallucinations).map(
    ([name, replacement]) => `- \`${name}\` does not exist. Use \`${replacement}\`.`,
  );
  return [
    MARKDOWN_HEADER,
    `# ${config.name}`,
    `> A small React design system. Import everything from \`${config.alias}\`. Only the exports listed on this page exist.`,
    [
      "## Docs",
      "",
      "- [All components](llms-components.txt): props, examples and Do/Don't for every component in one file",
      "- [Tokens](llms-tokens.txt): every color, space, radius and font size token",
    ].join("\n"),
    ["## Components", "", ...docs.map((doc) => `- [${doc.name}](components/${doc.name.toLowerCase()}.md): ${doc.summary}`)].join("\n"),
    [
      "## Exports",
      "",
      `This is the complete list of what \`${config.alias}\` exports.`,
      "",
      `- Components: ${inline(exportNames("component"))}`,
      `- Functions: ${inline(exportNames("value"))}`,
      `- Types: ${inline(exportNames("type"))}`,
    ].join("\n"),
    ["## Not exported", "", ...hallucinations].join("\n"),
    "",
  ].join("\n\n");
}

function generate(): Map<string, string> {
  const names = listComponents();
  const program = ts.createProgram(names.map(componentFile), loadCompilerOptions());
  const docs = names.map((name) => buildComponentDoc(program, name));
  const out = config.generatedDir;

  const files = new Map<string, string>();
  files.set(`${out}/llms.txt`, buildIndex(docs));
  files.set(
    `${out}/llms-components.txt`,
    [MARKDOWN_HEADER, ...docs.map((doc) => doc.markdown.replace(`${MARKDOWN_HEADER}\n\n`, "").trim())].join("\n\n") + "\n",
  );
  files.set(`${out}/llms-tokens.txt`, buildTokensDoc());
  for (const doc of docs) files.set(componentDocPath(doc.name), doc.markdown);
  files.set(TOKENS_CSS, buildTokensCss());
  return files;
}

function listGenerated(dir: string): string[] {
  const absolute = fromRoot(dir);
  if (!existsSync(absolute)) return [];
  return readdirSync(absolute, { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory() ? listGenerated(`${dir}/${entry.name}`) : [`${dir}/${entry.name}`],
  );
}

const files = generate();
const stale = listGenerated(config.generatedDir).filter((file) => !files.has(file));

if (process.argv.includes("--check")) {
  const outdated = [...files].filter(([file, content]) => {
    const target = fromRoot(file);
    return !existsSync(target) || readFileSync(target, "utf8") !== content;
  });
  const problems = [...outdated.map(([file]) => `out of date: ${file}`), ...stale.map((file) => `stale: ${file}`)];
  if (problems.length > 0) {
    console.error(`Generated files do not match their sources:\n${problems.map((line) => `  ${line}`).join("\n")}\nRun: pnpm docs:build`);
    process.exit(1);
  }
  console.log(`${files.size} generated files are up to date.`);
} else {
  for (const [file, content] of files) {
    mkdirSync(dirname(fromRoot(file)), { recursive: true });
    writeFileSync(fromRoot(file), content);
  }
  for (const file of stale) rmSync(fromRoot(file));
  console.log(`Wrote ${files.size} generated files.`);
}
