import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { formatReport } from "../checks";
import { fromRoot } from "../cli/lib/paths";
import {
  agentCommandLine,
  agentPrompt,
  createWorkspace,
  parseAgentOptions,
  runAgent,
  scoreWorkspace,
  type AgentRun,
  type Score,
  type Variant,
} from "./agent";
import { describeIntent, loadTasks, type Task } from "./tasks";

const HEADER = "<!-- Generated by evals/compare.ts. Do not edit. -->";
const RESULTS_DIR = fromRoot("evals/compare");
const DEFAULT_TASK = "login-form";

const VARIANTS: { variant: Variant; title: string; setup: string }[] = [
  {
    variant: "no-harness",
    title: "No harness",
    setup:
      "The playground, with the design system installed as a compiled package in `node_modules` (JavaScript and type declarations). No design system source, no `AGENTS.md`, no skill, no `ds` CLI, no generated docs.",
  },
  {
    variant: "harness",
    title: "Harness",
    setup: "The whole repo: `AGENTS.md`, the skills, the generated docs, the `ds` CLI and the edit hook.",
  },
];

interface Result {
  variant: Variant;
  title: string;
  setup: string;
  run: AgentRun;
  score: Score;
}

const problemCount = (result: Result) => result.score.violations.length;
const rulesOf = (result: Result) => [...new Set(result.score.violations.map((violation) => violation.rule))];

function outcome(result: Result): string {
  if (!result.score.targetExists) return "target file was not written";
  return problemCount(result) === 0 ? "passed" : `${problemCount(result)} problems`;
}

function intentOutcome(result: Result, task: Task): string {
  return `${task.intent.length - result.score.unmetIntent.length}/${task.intent.length}`;
}

function variantReport(result: Result, task: Task, date: string): string {
  const files = result.score.files.map((file) => `### ${file.path}\n\n\`\`\`tsx\n${file.source.trim()}\n\`\`\``);
  return [
    HEADER,
    `# ${result.title}: ${task.id}`,
    result.setup,
    [
      `- Date: ${date}`,
      `- Prompt: ${agentPrompt(task)}`,
      `- Agent command: \`${agentCommandLine(model)}\``,
      `- Model: ${result.run.models.join(", ") || "not reported"}`,
      `- Agent exit code: ${result.run.exitCode ?? "did not start"}`,
      `- Turns: ${result.run.turns ?? "not reported"}`,
      `- Duration: ${result.run.seconds}s`,
      `- \`ds check\`: ${outcome(result)}`,
      `- Intent: ${intentOutcome(result, task)}`,
    ].join("\n"),
    `## ds check report\n\n\`\`\`\n${formatReport(result.score.violations, result.score.files.length)}\n\`\`\``,
    `## Intent not met\n\n${result.score.unmetIntent.map((check) => `- ${describeIntent(check)}`).join("\n") || "None."}`,
    `## What the agent wrote\n\n${files.join("\n\n") || "Nothing in the pages directory."}`,
    `## What the agent said\n\n${result.run.output.trim() || "(no output)"}`,
    "",
  ].join("\n\n");
}

function summary(results: Result[], task: Task, date: string): string {
  const rows = results.map(
    (result) =>
      `| [${result.title}](${result.variant}.md) | ${outcome(result)} | ${intentOutcome(result, task)} | ${rulesOf(result).map((rule) => `\`${rule}\``).join(", ") || "none"} | ${result.run.turns ?? "n/a"} | ${result.run.seconds}s |`,
  );
  return [
    HEADER,
    `# Before and after: ${task.id}`,
    `One run of the same prompt against two copies of the repo, on ${date}. Scored by \`ds check\` and the task's intent checks.`,
    `> ${agentPrompt(task)}`,
    ["| Setup | `ds check` | Intent | Rules violated | Turns | Duration |", "| --- | --- | --- | --- | --- | --- |", ...rows].join("\n"),
    "This is a single run, not a benchmark. Agents are not deterministic, so run `pnpm evals:compare` to get your own result.",
    "",
  ].join("\n\n");
}

const { model, positional } = parseAgentOptions(process.argv.slice(2));
const taskId = positional[0] ?? DEFAULT_TASK;
const task = loadTasks().find((candidate) => candidate.id === taskId);
if (!task) {
  console.error(`No eval task named "${taskId}" in evals/tasks/.`);
  process.exit(2);
}

console.log(`Running "${task.id}" against ${VARIANTS.length} setups with: ${agentCommandLine(model)}`);
const results = await Promise.all(
  VARIANTS.map(async ({ variant, title, setup }): Promise<Result> => {
    const workspace = createWorkspace(variant);
    const run = await runAgent(workspace, agentPrompt(task), model);
    const score = await scoreWorkspace(workspace, task, variant);
    rmSync(workspace, { recursive: true, force: true });
    return { variant, title, setup, run, score };
  }),
);

const date = new Date().toISOString().slice(0, 10);
mkdirSync(RESULTS_DIR, { recursive: true });
for (const result of results) {
  writeFileSync(`${RESULTS_DIR}/${result.variant}.md`, variantReport(result, task, date));
  console.log(`${result.title}: ${outcome(result)} (${result.run.turns ?? "?"} turns, ${result.run.seconds}s)`);
}
writeFileSync(`${RESULTS_DIR}/README.md`, summary(results, task, date));
console.log("Wrote evals/compare/README.md, harness.md and no-harness.md.");

const agentFailed = results.some((result) => result.run.exitCode !== 0);
process.exit(agentFailed ? 1 : 0);
